using System; 

namespace Practice6
{
    public static class Block4
    {
        //  БЛОК 4 ПРОФЕСІЙНІ КОМПЛЕКСНІ ЗАДАЧІ ВАРІАНТ 1 
        public static void Run()
        {
            Console.WriteLine(" БЛОК 4 ЛОГИ ЗАВАНТАЖЕННЯ CPU ВАРІАНТ 1 ");

            Random rnd = new Random(42); 
            int n = 300; // Кількість замірів завантаження процесора за умовою варіанта 1
            double mu = 65.0; // Середнє базове навантаження CPU у відсотках
            double sigma = 12.0; // Стандартне відхилення навантаження CPU у відсотках

            double[] cpuLogs = new double[n]; // Масив для збереження 300 замірів CPU
            double sum = 0.0; // Сума всіх замірів для розрахунку середнього
            for (int i = 0; i < n; i++) // Симулюємо 300 записів у лог-файлі
            {
                double u1 = 1.0 - rnd.NextDouble(); // Перше випадкове число (0, 1]
                double u2 = 1.0 - rnd.NextDouble(); // Друге випадкове число (0, 1]
                double z = Math.Sqrt(-2.0 * Math.Log(u1)) * Math.Cos(2.0 * Math.PI * u2); // Стандартна нормальна величина
                double val = mu + sigma * z; // Завантаження CPU у поточний момент

                if (val < 0.0) // Якщо число вийшло менше 0 відсотків — обмежуємо нулем
                {
                    val = 0.0; // Мінімально можливе завантаження процесора
                }
                if (val > 100.0) // Якщо число перевищило 100 відсотків — обмежуємо сотнею
                {
                    val = 100.0; // Максимально можливе завантаження процесора
                }

                cpuLogs[i] = val; // Записуємо замір у масив
                sum += val; // Додаємо замір до загальної суми
            }

            Array.Sort(cpuLogs); // Сортуємо заміри за зростанням для медіани та гістограми
            double mean = sum / n; // Середнє завантаження процесора

            double sumSq = 0.0; // Сума квадратів відхилень від середнього
            for (int i = 0; i < n; i++) // Рахуємо розкид значень навантаження
            {
                double d = cpuLogs[i] - mean; // Відхилення конкретного заміру
                sumSq += d * d; // Накопичуємо квадрат відхилення
            }
            double s = Math.Sqrt(sumSq / (n - 1)); // Виправлене стандартне відхилення
            double median = (cpuLogs[n / 2 - 1] + cpuLogs[n / 2]) / 2.0; // Медіана для парної кількості 300 елементів
            double cv = (s / mean) * 100.0; // Коефіцієнт варіації навантаження у відсотках

            int k = 1 + (int)Math.Floor(3.322 * Math.Log10(n)); // Кількість інтервалів гістограми за Стерджесом
            double xMin = cpuLogs[0]; // Мінімальне зафіксоване завантаження CPU
            double xMax = cpuLogs[n - 1]; // Максимальне зафіксоване завантаження CPU
            double h = (xMax - xMin) / k; // Ширина інтервалу для гістограми

            Console.WriteLine($"Характеристики CPU (n={n}) -> x_bar={mean:F2}%, S={s:F2}%, Медіана={median:F2}%, V={cv:F2}%");
            Console.WriteLine("Інтервальний ряд для гістограми навантаження CPU");

            for (int i = 0; i < k; i++) // Будуємо інтервали гістограми
            {
                double left = xMin + i * h; // Ліва межа інтервалу
                double right = xMin + (i + 1) * h; // Права межа інтервалу
                int cnt = 0; // Кількість замірів в інтервалі

                for (int j = 0; j < n; j++) // Перевіряємо всі 300 замірів
                {
                    if (i < k - 1) // Для всіх інтервалів крім останнього права межа не включно
                    {
                        if (cpuLogs[j] >= left && cpuLogs[j] < right) // Перевірка потрапляння в інтервал
                        {
                            cnt++; // Збільшуємо лічильник інтервалу
                        }
                    }
                    else // Для останнього інтервалу включаємо праву межу
                    {
                        if (cpuLogs[j] >= left && cpuLogs[j] <= right + 1e-9) // Перевірка потрапляння включно з максимумом
                        {
                            cnt++; // Збільшуємо лічильник останнього інтервалу
                        }
                    }
                }

                double wi = (double)cnt / n; // Відносна частота інтервалу
                Console.WriteLine($"[{left,6:F2}%; {right,6:F2}%) | n={cnt,3} | w={wi:F4}");
            }

            if (cv < 33.0) // Якщо коефіцієнт варіації менший за 33 відсотки — навантаження однорідне
            {
                Console.WriteLine("Висновок -> Оскільки V < 33%, навантаження CPU є однорідним та стабільним.");
            }
            else // Якщо перевищує 33 відсотки — навантаження неоднорідне зі стрибками
            {
                Console.WriteLine("Висновок -> Оскільки V > 33%, навантаження CPU є неоднорідним.");
            }
        }
    }
}