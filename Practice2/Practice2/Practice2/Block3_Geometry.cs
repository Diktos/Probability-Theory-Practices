using System; // дає консольний вивід, базові типи та математичні функції

namespace Practice2
{
    //  БЛОК 3  
    // геометрична ймовірність та метод Монте-Карло для області D
    public static class Block3_Geometry
    {
        public static void Run(Random rnd)
        {
            Console.WriteLine("БЛОК 3. Геометрична ймовірність складної області D");

            // аналітичне знаходження точки перетину параболи та прямої: розв'язок рівняння x^2 + x - 1 = 0
            double x0 = (Math.Sqrt(5.0) - 1.0) / 2.0;

            // первісна для визначеного інтеграла від різниці функцій: F(x) = x^3/3 + x^2/2 - x
            double F(double x) => (x * x * x) / 3.0 + (x * x) / 2.0 - x;

            // формула Ньютона-Лейбніца для точної площі області D на проміжку від x0 до 1
            double sDTheo = F(1.0) - F(x0);

            Console.WriteLine($"Точка перетину x0 = {x0:F6}");
            Console.WriteLine($"Точна площа S(D) = {sDTheo:F6}\n");

            int[] nValues = { 100, 1000, 10000, 100000, 1000000 }; // вибірки точок для перевірки збіжності за ЗВЧ
            Console.WriteLine($"{"N точок",10} | {"M влуч.",10} | {"W(D) = M/N",14} | {"S(D) теор",12} | {"Похибка Δ",12}");
            Console.WriteLine(new string('-', 66));

            // тестування для кожного обсягу генерації
            foreach (int n in nValues)
            {
                int m = 0; // кількість випадкових точок, які потрапили всередину фігури D

                // генерація n точок у квадраті одиничної площі
                for (int i = 0; i < n; i++)
                {
                    double x = rnd.NextDouble(); // координата x, рівномірно розподілена від 0.0 до 1.0
                    double y = rnd.NextDouble(); // координата y, рівномірно розподілена від 0.0 до 1.0

                    // геометрична умова: точка знаходиться під параболою y <= x^2 та над прямою y >= 1 - x
                    if (y <= x * x && y >= 1.0 - x)
                    {
                        m++; // фіксуємо влучання в область
                    }
                }

                // геометрична ймовірність Монте-Карло: відношення влучань m до загальної площі квадрата n
                double w = (double)m / n;

                // модуль різниці між Монте-Карло та точним інтегралом
                double delta = Math.Abs(w - sDTheo);

                Console.WriteLine($"{n,10} | {m,10} | {w,14:F6} | {sDTheo,12:F6} | {delta,12:F6}");
            }
            Console.WriteLine();
        }
    }
}