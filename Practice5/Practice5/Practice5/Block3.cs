using System; 

namespace Practice5
{
    public static class Block3
    {
        public static void Run()
        {
            Console.WriteLine(" БЛОК 3 ПЕРЦЕНТИЛЬНИЙ АНАЛІЗ ЗАТРИМОК ПЗ LATENCY TAIL ");

            Random rnd = new Random(42); 
            int n = 100000; // Кількість запитів для моделювання затримок (100 000)

            double[] latencies = new double[n]; // Масив для збереження часу затримки кожного запиту
            double sum1 = 0.0; // Сума всіх затримок для обчислення середнього

            for (int i = 0; i < n; i++) // Цикл генерації 100 000 запитів до системи
            {
                double x; // Змінна для часу затримки поточного запиту в мілісекундах
                if (rnd.NextDouble() < 0.90) // У 90% випадків запит штатний за нормальним законом N(20, 4^2)
                {
                    double u1 = 1.0 - rnd.NextDouble(); 
                    double u2 = rnd.NextDouble(); 
                    double z0 = Math.Sqrt(-2.0 * Math.Log(u1)) * Math.Cos(2.0 * Math.PI * u2); // Формула Бокса-Мюллера N(0,1)
                    x = 20.0 + 4.0 * z0; // Переводимо у нормальний розподіл із середнім 20 мс і сигмою 4 мс
                }
                else // У решті 10% випадків — важкий запит або збір сміття GC за законом Exp(0.01)
                {
                    double u = rnd.NextDouble(); // Випадкове рівномірне число від 0 до 1
                    x = -Math.Log(1.0 - u) / 0.01; // Обернена функція для показникового закону із середнім 100 мс
                }

                latencies[i] = x; // Записуємо отриману затримку у масив
                sum1 += x; // Додаємо затримку до загальної суми
            }

            double mean = sum1 / n; // Вибіркове середнє значення затримки
            double sum2 = 0.0; // Сума квадратів відхилень для розрахунку сигми

            for (int i = 0; i < n; i++) // Проходимо по масиву для оцінки розкиду затримок
            {
                double diff = latencies[i] - mean; // Відхилення конкретної затримки від середньої
                sum2 += diff * diff; // Накопичуємо квадрат відхилення
            }

            double sigma = Math.Sqrt(sum2 / n); // Вибіркове середньоквадратичне відхилення затримки

            Array.Sort(latencies); // Сортуємо масив затримок за зростанням для взяття перцентилів

            double p50 = latencies[(int)(n * 0.50)]; // Середина відсортованого масиву
            double p90 = latencies[(int)(n * 0.90)]; // Межа для 90% запитів
            double p95 = latencies[(int)(n * 0.95)]; // Межа для 95% запитів
            double p99 = latencies[(int)(n * 0.99)]; // Хвіст найповільнішого 1% запитів

            Console.WriteLine($"Середнє={mean:F5} мс, Сигма={sigma:F5} мс");
            Console.WriteLine($"Перцентилі: p50={p50:F5} мс, p90={p90:F5} мс, p95={p95:F5} мс, p99={p99:F5} мс");
            Console.WriteLine();
        }
    }
}