using System; 

namespace Practice4
{
    public static class Block1
    {
        public static void Run()
        {
            Console.WriteLine(" БЛОК 1 МОДЕЛЮВАННЯ БАЙЄСІВСЬКОГО ОНОВЛЕННЯ ЙМОВІРНОСТЕЙ ");

            Random rnd = new Random(42); 
            int[] sizes = { 100, 1000, 10000, 100000, 1000000 }; 

            double pH1 = 0.90; // Початковий шанс звичайного користувача
            double pH2 = 0.08; // Початковий шанс пошукового бота
            double pH3 = 0.02; // Початковий шанс хакерської атаки

            double pA_H1 = 0.01; // Шанс спецсимволів у звичайного користувача
            double pA_H2 = 0.25; // Шанс спецсимволів у бота
            double pA_H3 = 0.90; // Шанс спецсимволів під час атаки

            double pA_theo = pH1 * pA_H1 + pH2 * pA_H2 + pH3 * pA_H3; // Повна теоретична ймовірність тривоги A (0.047)
            double pH3_A_theo = (pH3 * pA_H3) / pA_theo; // Теоретична ймовірність атаки за формулою Байєса (0.38298)

            foreach (int n in sizes) // Перебираємо кожен обсяг вибірки N по черзі
            {
                int countA = 0; // Лічильник усіх запитів, де спрацювала тривога A
                int countH1_A = 0; // Лічильник звичайних користувачів серед тривожних запитів
                int countH2_A = 0; // Лічильник ботів серед тривожних запитів
                int countH3_A = 0; // Лічильник реальних атак серед тривожних запитів

                for (int i = 0; i < n; i++) // Цикл прогону n випадкових запитів до сервера
                {
                    double rH = rnd.NextDouble(); // Випадкове число від 0 до 1 для вибору хто зайшов на сервер
                    int h; // Номер гіпотези (1 - користувач, 2 - бот, 3 - атака)
                    double pA_cond; // Шанс появи спецсимволів для обраної категорії

                    if (rH < pH1) // Якщо випало менше 0.90 — це звичайний користувач
                    {
                        h = 1; // Фіксуємо гіпотезу H1
                        pA_cond = pA_H1; // Беремо шанс тривоги для користувача (0.01)
                    }
                    else if (rH < pH1 + pH2) // Якщо випало від 0.90 до 0.98 — це пошуковий бот
                    {
                        h = 2; // Фіксуємо гіпотезу H2
                        pA_cond = pA_H2; // Беремо шанс тривоги для бота (0.25)
                    }
                    else // Інакше (останні 2% від 0.98 до 1.00) — це атака
                    {
                        h = 3; // Фіксуємо гіпотезу H3
                        pA_cond = pA_H3; // Беремо шанс тривоги для атаки (0.90)
                    }

                    bool isA = rnd.NextDouble() < pA_cond; // Перевіряємо чи з'явилися спецсимволи в поточному запиті
                    if (isA) // Якщо тривога спрацювала — оновлюємо статистику
                    {
                        countA++; // Збільшуємо загальний лічильник тривог
                        if (h == 1) countH1_A++; // Якщо це був користувач — плюсуємо його
                        else if (h == 2) countH2_A++; // Якщо це був бот — плюсуємо бота
                        else countH3_A++; // Якщо це була атака — плюсуємо атаку
                    }
                }

                double wA = (double)countA / n; // Статистична частота появи ознаки A серед усіх запитів
                double wH1_A = countA > 0 ? (double)countH1_A / countA : 0.0; // Частка користувачів серед тривог
                double wH2_A = countA > 0 ? (double)countH2_A / countA : 0.0; // Частка ботів серед тривог
                double wH3_A = countA > 0 ? (double)countH3_A / countA : 0.0; // Частка атак серед тривог
                double error = Math.Abs(wH3_A - pH3_A_theo); // Абсолютна похибка між досвідом і теорією Байєса

                Console.WriteLine($"N={n}: W(A)={wA:F5}, W(H1|A)={wH1_A:F5}, W(H2|A)={wH2_A:F5}, W(H3|A)={wH3_A:F5}, Похибка={error:F5}");
            }
            Console.WriteLine();
        }
    }
}