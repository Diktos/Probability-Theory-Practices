using System; // Базові функції консолі, математики та генератор випадкових чисел

namespace Practice3 
{
    public class Block2 
    {
        public static void Run() 
        {
            Console.WriteLine(" БЛОК 2 ПАРАЛЕЛЬНІ ПОТОКИ ВАРІАНТ 4 ");

            Random rand = new Random(42); 
            int n = 100000; // Кількість симуляцій запусків системи за умовою завдання

            double pT1 = 0.90; // Ймовірність безпомилкового завершення першого потоку T1
            double pT2 = 0.80; // Ймовірність безпомилкового завершення другого потоку T2
            double pT3 = 0.70; // Ймовірність безпомилкового завершення третього потоку T3

            double theoA = pT1 * pT2 * pT3; // Теоретична ймовірність події A (усі 3 потоки без помилок) = 0.504
            double theoB = 1.0 - theoA; // Теоретична ймовірність події B (хоча б 1 потік з помилкою) = 0.496
            double theoOneErr = (0.10 * 0.80 * 0.70) + (0.90 * 0.20 * 0.70) + (0.90 * 0.80 * 0.30); // Теоретична ймовірність рівно однієї помилки = 0.398

            int countA = 0; // Лічильник запусків, де всі 3 потоки відпрацювали без помилок (подія A)
            int countB = 0; // Лічильник запусків, де хоча б один потік дав збій (подія B)
            int countOneErr = 0; // Лічильник запусків, де помилився рівно один потік із трьох
            int countAB = 0; // Лічильник одночасного настання подій A і B (перевірка несумісності)
            int countAorB = 0; // Лічильник настання події A або події B (перевірка повної групи)

            for (int i = 0; i < n; i++) // Цикл моделювання 100 000 запусків трьох потоків
            {
                bool ok1 = rand.NextDouble() < pT1; 
                bool ok2 = rand.NextDouble() < pT2;
                bool ok3 = rand.NextDouble() < pT3; 

                int errors = 0; // Змінна для підрахунку кількості потоків із помилкою в поточному запуску

                if (!ok1) // Якщо перший потік завершився з помилкою — додаємо помилку
                {
                    errors++; // +1 помилка до поточного запуску
                }

                if (!ok2) 
                {
                    errors++; 
                }

                if (!ok3) 
                {
                    errors++; 
                }

                bool eventA = (errors == 0); // Подія A настала, якщо кількість помилок дорівнює нулю
                bool eventB = (errors >= 1); // Подія B настала, якщо є хоча б одна помилка

                if (eventA) 
                {
                    countA++; 
                }

                if (eventB) // Якщо стався хоча б один збій — фіксуємо подію B
                {
                    countB++; // Додаємо одиницю до лічильника події B
                }

                if (errors == 1) // Якщо помилився рівно один потік — фіксуємо цю подію
                {
                    countOneErr++; // Додаємо одиницю до лічильника рівно однієї помилки
                }

                if (eventA && eventB) // Якщо одночасно сталися A і B — фіксуємо перетин
                {
                    countAB++; // Додаємо одиницю до лічильника перетину A та B
                }

                if (eventA || eventB) // Якщо сталася подія A або подія B — фіксуємо об'єднання
                {
                    countAorB++; // Додаємо одиницю до лічильника об'єднання A або B
                }
            }

            double wA = (double)countA / n; // Статистична оцінка ймовірності події A
            double wB = (double)countB / n; // Статистична оцінка ймовірності події B
            double wOneErr = (double)countOneErr / n; // Статистична оцінка ймовірності рівно однієї помилки
            double wAB = (double)countAB / n; // Статистична оцінка перетину P(A і B)
            double wAorB = (double)countAorB / n; // Статистична оцінка об'єднання P(A або B)
            double wAgivenB = countB > 0 ? (double)countAB / countB : 0.0; // Оцінка умовної ймовірності P(A|B)
            double wBgivenA = countA > 0 ? (double)countAB / countA : 0.0; // Оцінка умовної ймовірності P(B|A)

            Console.WriteLine($"P(A) усі 3 без помилок: стат={wA:F5}, теор={theoA:F5}, похибка={Math.Abs(wA - theoA):F5}"); // Виводимо порівняння для події A
            Console.WriteLine($"P(B) хоча б 1 помилка:  стат={wB:F5}, теор={theoB:F5}, похибка={Math.Abs(wB - theoB):F5}"); // Виводимо порівняння для події B
            Console.WriteLine($"P(рівно 1 помилка):     стат={wOneErr:F5}, теор={theoOneErr:F5}, похибка={Math.Abs(wOneErr - theoOneErr):F5}"); // Виводимо порівняння для однієї помилки
            Console.WriteLine($"P(A і B)={wAB:F5}, P(A або B)={wAorB:F5}, P(A|B)={wAgivenB:F5}, P(B|A)={wBgivenA:F5}"); // Виводимо перевірку теорем додавання та умовної ймовірності
            Console.WriteLine(); 
        }
    }
}