using System; // Математичні функції та консольний вивід

namespace Practice8
{
    public static class Block1
    {
        //  БЛОК 1 ПЕРЕВІРКА ЗАКОНУ РОЗПОДІЛУ ЗА КРИТЕРІЄМ ПІРСОНА ХІ КВАДРАТ 
        public static void Run()
        {
            Console.WriteLine(" БЛОК 1 ПЕРЕВІРКА НОРМАЛЬНОСТІ ЗА КРИТЕРІЄМ ПІРСОНА ");

            double[] leftEdges = { 60, 75, 90, 105, 120, 135, 150, 165 }; // Ліві межі 8 інтервалів у мс
            double[] rightEdges = { 75, 90, 105, 120, 135, 150, 165, 180 }; // Праві межі 8 інтервалів у мс
            int[] observed = { 8, 22, 44, 52, 40, 20, 10, 4 }; // Спостережувані частоти Oi за умовою
            int n = 200; // Загальний обсяг вибірки затримок API
            int k = 8; // Кількість інтервалів
            double xBar = 112.5; // Вибіркове середнє у мс
            double s = 21.4; // Виправлене стандартне відхилення у мс

            double chi2Obs = 0.0; // Накопичувач для спостережуваного значення критерію Пірсона

            for (int i = 0; i < k; i++) // Обчислюємо теоретичну ймовірність та очікувану частоту для кожного інтервалу
            {
                double z1 = (leftEdges[i] - xBar) / s; // Нормована ліва межа інтервалу
                double z2 = (rightEdges[i] - xBar) / s; // Нормована права межа інтервалу
                double pi = NormCdf(z2) - NormCdf(z1); // Теоретична ймовірність потрапляння в інтервал за функцією Лапласа
                double ei = n * pi; // Очікувана теоретична частота Ei = n * pi
                double diff = observed[i] - ei; // Різниця між реальною і теоретичною частотою
                double contrib = (diff * diff) / ei; // Внесок інтервалу в статистику хі-квадрат
                chi2Obs += contrib; // Додаємо внесок до загальної суми

                Console.WriteLine($"[{leftEdges[i],3:F0}; {rightEdges[i],3:F0}) | Oi={observed[i],2} | pi={pi:F5} | Ei={ei,6:F2} | Внесок={contrib:F4}");
            }

            int df = k - 1 - 2; // Ступені свободи (8 інтервалів мінус 1 і мінус 2 оцінені параметри)
            double chi2Crit = 11.0705; // Критичне значення хі-квадрат для рівня значущості 0.05 і df=5
            double pValue = 0.1242; // Досягнутий рівень значущості p-value для отриманої статистики

            Console.WriteLine($"chi2_спост={chi2Obs:F4}, df={df}, chi2_крит={chi2Crit:F4}, p-value={pValue:F4}");

            if (chi2Obs < chi2Crit) // Якщо спостережуване значення менше критичного — нульову гіпотезу приймаємо
            {
                Console.WriteLine("Висновок -> Оскільки chi2_спост < chi2_крит (p-value > 0.05), немає підстав відхиляти H0 (розподіл нормальний).");
            }
            else // Інакше відхиляємо нульову гіпотезу
            {
                Console.WriteLine("Висновок -> Відхиляємо гіпотезу H0 про нормальний розподіл.");
            }
            Console.WriteLine();
        }

        // Функція стандартного нормального розподілу Ф(z) за наближенням Абрамовіца і Стегана
        private static double NormCdf(double x)
        {
            int sign = x < 0 ? -1 : 1; // Зберігаємо знак аргументу
            double z = Math.Abs(x) / Math.Sqrt(2.0); // Переходимо до аргументу функції помилок erf
            double t = 1.0 / (1.0 + 0.3275911 * z); // Допоміжна змінна для полінома
            double erf = 1.0 - (((((1.061405429 * t - 1.453152027) * t) + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t * Math.Exp(-z * z); // Наближення erf(z)
            return 0.5 * (1.0 + sign * erf); // Повертаємо ймовірність P(Z <= x)
        }
    }
}