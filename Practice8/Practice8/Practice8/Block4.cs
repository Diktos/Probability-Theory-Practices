using System; // Математичні операції та консольний вивід

namespace Practice8
{
    public static class Block4
    {
        //  БЛОК 4 ПРОФЕСІЙНІ КОМПЛЕКСНІ ЗАДАЧІ ВАРІАНТ 1 ПОРІВНЯННЯ ДАТА ЦЕНТРІВ 
        public static void Run()
        {
            Console.WriteLine(" БЛОК 4 T ТЕСТ ЗАТРИМОК ДВОХ ДАТА ЦЕНТРІВ КИЇВ VS ФРАНКФУРТ ВАРІАНТ 1 ");

            int n1 = 100; // Кількість замірів затримки для дата-центру Київ
            double xBar1 = 24.0; // Середня затримка у Києві в мс
            double s1 = 4.0; // Стандартне відхилення затримки у Києві в мс

            int n2 = 100; // Кількість замірів затримки для дата-центру Франкфурт
            double xBar2 = 42.0; // Середня затримка у Франкфурті в мс
            double s2 = 6.0; // Стандартне відхилення затримки у Франкфурті в мс

            int df = n1 + n2 - 2; // Кількість ступенів свободи (100 + 100 - 2 = 198)
            double sp2 = ((n1 - 1) * s1 * s1 + (n2 - 1) * s2 * s2) / df; // Об'єднана дисперсія двох вибірок
            double sp = Math.Sqrt(sp2); // Об'єднане стандартне відхилення
            double tObs = (xBar1 - xBar2) / Math.Sqrt(sp2 * (1.0 / n1 + 1.0 / n2)); // Спостережувана t-статистика Стьюдента
            double tCrit = 2.6009; // Двостороннє критичне значення для рівня значущості alpha = 0.01 та df = 198
            double cohenD = (xBar1 - xBar2) / sp; // Розмір ефекту за Коеном

            Console.WriteLine($"Київ (n1={n1}, x_bar1={xBar1:F1} мс, S1={s1:F1}) vs Франкфурт (n2={n2}, x_bar2={xBar2:F1} мс, S2={s2:F1})");
            Console.WriteLine($"Результати тесту (alpha=0.01) -> Sp^2={sp2:F4}, Sp={sp:F4}, t_спост={tObs:F4}, t_крит={tCrit:F4}, d Коена={cohenD:F4}");

            if (Math.Abs(tObs) > tCrit) // Якщо модуль t_спост перевищує критичний поріг — різниця між дата-центрами доведена
            {
                Console.WriteLine("Висновок -> Оскільки |t_спост| = 24.9615 > t_крит = 2.6009 (p-value < 0.0001), відхиляємо H0 (затримка у Києві значуще менша).");
            }
            else // Інакше різниця статистично незначуща
            {
                Console.WriteLine("Висновок -> Немає підстав відхиляти нульову гіпотезу H0.");
            }
        }
    }
}