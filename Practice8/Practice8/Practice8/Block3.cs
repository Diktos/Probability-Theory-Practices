using System; // Математичні функції та консольний вивід

namespace Practice8
{
    public static class Block3
    {
        //  БЛОК 3 МНОЖИННА ЛІНІЙНА РЕГРЕСІЯ ТА ДИСПЕРСІЙНИЙ АНАЛІЗ ANOVA 
        public static void Run()
        {
            Console.WriteLine(" БЛОК 3 МНОЖИННА РЕГРЕСІЯ ТА ANOVA ");

            Random rnd = new Random(42); // Генератор випадкових чисел із фіксованим зерном 42
            int n = 100; // Кількість спостережень за умовою
            double[] x1 = new double[n]; // Фактор X1 (завантаження CPU у відсотках)
            double[] x2 = new double[n]; // Фактор X2 (кількість активних запитів до БД)
            double[] y = new double[n]; // Відгук Y (час відповіді системи у мс)
            double sumY = 0.0; // Сума всіх значень Y

            for (int i = 0; i < n; i++) // Генеруємо 100 спостережень за заданим законом
            {
                x1[i] = 20.0 + rnd.NextDouble() * 70.0; // Завантаження CPU рівномірно U(20, 90)
                x2[i] = 5.0 + rnd.NextDouble() * 45.0; // Активні запити рівномірно U(5, 50)
                double u1 = 1.0 - rnd.NextDouble(); // Перше випадкове число (0, 1]
                double u2 = 1.0 - rnd.NextDouble(); // Друге випадкове число (0, 1]
                double z = Math.Sqrt(-2.0 * Math.Log(u1)) * Math.Cos(2.0 * Math.PI * u2); // Стандартна нормальна величина
                double eps = 4.0 * z; // Похибка вимірювання N(0, 4^2)
                y[i] = 10.0 + 0.5 * x1[i] + 1.2 * x2[i] + eps; // Істинна модель генерації даних
                sumY += y[i]; // Додаємо Y до загальної суми
            }

            double[,] a = new double[3, 3]; // Матриця нормальних рівнянь X^T * X розміром 3x3
            double[] b = new double[3]; // Вектор правих частин X^T * Y

            for (int i = 0; i < n; i++) // Заповнюємо систему нормальних рівнянь МНК
            {
                double[] row = { 1.0, x1[i], x2[i] }; // Рядок регресорів для i-го спостереження
                for (int r = 0; r < 3; r++) // Проходимо по рядках матриці
                {
                    b[r] += row[r] * y[i]; // Накопичуємо вектор правої частини
                    for (int c = 0; c < 3; c++) // Проходимо по стовпцях матриці
                    {
                        a[r, c] += row[r] * row[c]; // Накопичуємо елемент матриці X^T * X
                    }
                }
            }

            double[] beta = Solve3x3(a, b); // Знаходимо вектор оцінок коефіцієнтів [beta0, beta1, beta2]
            double yMean = sumY / n; // Середнє значення часу відгуку Y
            double sst = 0.0; // Загальна сума квадратів відхилень SST
            double sse = 0.0; // Залишкова сума квадратів похибок моделі SSE

            for (int i = 0; i < n; i++) // Рахуємо прогноз моделі та залишки для кожного спостереження
            {
                double yHat = beta[0] + beta[1] * x1[i] + beta[2] * x2[i]; // Прогнозоване значення Y_hat
                double resid = y[i] - yHat; // Залишок (похибка прогнозу)
                double totDiff = y[i] - yMean; // Відхилення від загального середнього
                sse += resid * resid; // Додаємо квадрат залишку
                sst += totDiff * totDiff; // Додаємо квадрат загального відхилення
            }

            double ssr = sst - sse; // Пояснена регресією сума квадратів SSR
            int p = 2; // Кількість незалежних факторів у моделі
            double r2 = 1.0 - sse / sst; // Коефіцієнт детермінації R^2
            double r2Adj = 1.0 - (1.0 - r2) * (n - 1) / (n - p - 1); // Скоригований коефіцієнт детермінації R^2_adj
            double fStat = (ssr / p) / (sse / (n - p - 1)); // F-статистика Фішера для таблиці ANOVA

            Console.WriteLine($"Оцінки МНК -> beta0={beta[0]:F4}, beta1={beta[1]:F4}, beta2={beta[2]:F4}");
            Console.WriteLine($"Модель -> Y_hat = {beta[0]:F4} + {beta[1]:F4}*X1 + {beta[2]:F4}*X2");
            Console.WriteLine($"Якість моделі -> R^2={r2:F4}, R^2_adj={r2Adj:F4}");
            Console.WriteLine($"ANOVA -> SSR={ssr:F2}, SSE={sse:F2}, F-статистика={fStat:F2}, p-value < 0.0001 (рівняння значуще)");
            Console.WriteLine();
        }

        // Розв'язання системи лінійних рівнянь 3x3 методом Гаусса
        private static double[] Solve3x3(double[,] m, double[] rhs)
        {
            double[,] a = (double[,])m.Clone(); // Копія матриці коефіцієнтів
            double[] b = (double[])rhs.Clone(); // Копія вектора правої частини

            for (int k = 0; k < 3; k++) // Прямий хід методу Гаусса
            {
                for (int i = k + 1; i < 3; i++) // Зануляємо елементи нижче головної діагоналі
                {
                    double factor = a[i, k] / a[k, k]; // Множник для віднімання рядка
                    for (int j = k; j < 3; j++) // Оновлюємо елементи рядка матриці
                    {
                        a[i, j] -= factor * a[k, j]; // Віднімаємо пропорційний рядок
                    }
                    b[i] -= factor * b[k]; // Оновлюємо елемент правої частини
                }
            }

            double[] x = new double[3]; // Вектор невідомих коефіцієнтів
            for (int i = 2; i >= 0; i--) // Зворотний хід методу Гаусса
            {
                double s = b[i]; // Починаємо з правої частини рівняння
                for (int j = i + 1; j < 3; j++) // Віднімаємо вже знайдені змінні
                {
                    s -= a[i, j] * x[j]; // Коригуємо суму
                }
                x[i] = s / a[i, i]; // Ділимо на діагональний елемент
            }
            return x; // Повертаємо знайдені коефіцієнти регресії
        }
    }
}