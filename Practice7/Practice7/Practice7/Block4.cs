using System; // Математичні операції та вивід у консоль

namespace Practice7
{
    public static class Block4
    {
        //  БЛОК 4 ПРОФЕСІЙНІ КОМПЛЕКСНІ ЗАДАЧІ ВАРІАНТ 1 SLA ЗАТРИМКИ 
        public static void Run()
        {
            Console.WriteLine(" БЛОК 4 ОЦІНКА SLA ЗАТРИМКИ ВАРІАНТ 1 ");

            int n = 60; // Кількість замірів затримки за варіантом 1
            double xBar = 95.0; // Вибіркове середнє затримки у мс
            double s = 12.0; // Виправлене стандартне відхилення у мс
            double slaLimit = 100.0; // Гранично допустима затримка за угодою SLA у мс
            double tCrit = 2.00100; // Квантиль розподілу Стьюдента для надії 95% і ступенів свободи df=59

            double margin = tCrit * s / Math.Sqrt(n); // Гранична похибка середнього
            double ciLow = xBar - margin; // Нижня межа 95% довірчого інтервалу
            double ciHigh = xBar + margin; // Верхня межа 95% довірчого інтервалу

            Console.WriteLine($"Вхідні дані -> n={n}, x_bar={xBar:F2} мс, S={s:F2} мс, поріг SLA={slaLimit:F2} мс");
            Console.WriteLine($"95% довірчий інтервал для середньої затримки -> [{ciLow:F2}; {ciHigh:F2}] мс (ширина {(ciHigh - ciLow):F2} мс)");

            if (ciHigh <= slaLimit) // Якщо навіть верхня межа інтервалу не перевищує 100 мс — норматив SLA виконано
            {
                Console.WriteLine("Висновок -> Верхня межа 98.10 мс <= 100 мс, тому з надійністю 95% вимога SLA виконується.");
            }
            else // Якщо верхня межа перевищує поріг — є ризик порушення SLA
            {
                Console.WriteLine("Висновок -> Верхня межа перевищує 100 мс, вимога SLA порушується.");
            }
        }
    }
}